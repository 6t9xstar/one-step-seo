  assert.equal(isDevOrStagingHost("dev.to", "example.com"), false, "dev.to is a real site");
  assert.equal(isDevOrStagingHost("blog.example.com", "example.com"), false);
  assert.equal(isDevOrStagingHost("staging.other.com", "example.com"), false);
  assert.equal(isDevOrStagingHost("8.8.8.8", "example.com"), false);
  assert.equal(isDevOrStagingHost("", "example.com"), false);

  assert.equal(isInternalSearchUrl("https://a.test/search/shoes/"), true);
  assert.equal(isInternalSearchUrl("https://a.test/?s=shoes"), true);
  assert.equal(isInternalSearchUrl("https://a.test/products?q=red"), true);
