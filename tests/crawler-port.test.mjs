test("crawlSite retries a 503, skips trap URLs, and never requests them", async () => {
  clearSiteFilesCache();
  clearSitemapUrlsCache();
  const site = await serve((req, res, hits) => {
    const path = new URL(req.url ?? "/", "http://x").pathname;
    if (path === "/") {
      res.writeHead(200, { "content-type": "text/html" });
      res.end(
        html(
          "Home",
          [
            '<a href="/flaky">Flaky</a>',
            '<a href="/wp-json/wp/v2/posts">API</a>',
            '<a href="/blog/feed/">Feed</a>',
            '<a href="/news/?e-page-1a2b3c=2">Page 2</a>',
            '<a href="our-team/">Relative</a>',
            '<a href="/our-team/our-team/">Loop</a>',
            '<a href="7FG4+8Q Springfield">Directions</a>',
          ].join(""),
        ),
      );
      return;
    }
    if (path === "/flaky") {
      if ((hits.get(path) ?? 0) === 1) {
        res.writeHead(503, { "content-type": "text/html", "retry-after": "0" });
        res.end("busy");
        return;
      }
      res.writeHead(200, { "content-type": "text/html" });
      res.end(html("Flaky page", "<p>Back up.</p>"));
      return;
    }
    if (path === "/our-team/") {
      res.writeHead(200, { "content-type": "text/html" });
      res.end(html("Team", '<a href="our-team/">Team again</a>'));
      return;
    }
    res.writeHead(404, { "content-type": "text/html" });
    res.end("missing");
  });
  try {
    /** @type {string[]} */
    const warnings = [];
    const c = await crawlSite(
      `${site.base}/`,
      { pages: 20, crawl: "links", all: true, delay: 0 },
      { warn: (m) => warnings.push(m) },
    );
    const audited = c.pages.map((p) => new URL(p.finalUrl).pathname);
    assert.ok(audited.includes("/flaky"), "the 503 page was retried and audited");
    assert.equal(site.hits.get("/flaky"), 2);
    assert.ok(
      warnings.some((w) => /answered HTTP 503 — retry 1/.test(w)),
      warnings.join("\n"),
    );
    for (const trap of ["/wp-json/wp/v2/posts", "/blog/feed/", "/news/", "/our-team/our-team/"]) {
      assert.equal(site.hits.get(trap), undefined, `${trap} is never requested`);
    }
    assert.ok(audited.includes("/our-team/"), "the real page is still crawled");
    assert.ok(c.trapsSkipped >= 4, `trapsSkipped=${c.trapsSkipped}`);
    assert.equal(site.hits.get("/7FG4+8Q%20Springfield"), undefined, "text in an href is not crawled");
    assert.equal(c.stoppedReason, "");
  } finally {
    await site.close();
  }
});

test("crawlSite stops after three pages in a row are turned away by a firewall", async () => {
  clearSiteFilesCache();
  clearSitemapUrlsCache();
  const links = Array.from({ length: 8 }, (_, i) => `<a href="/p${i}">P${i}</a>`).join("");
  const site = await serve((req, res) => {
    const path = new URL(req.url ?? "/", "http://x").pathname;
    if (path === "/") {
      res.writeHead(200, { "content-type": "text/html" });
      res.end(html("Home", links));
      return;
    }
    res.writeHead(403, { "content-type": "text/html", server: "cloudflare" });
    res.end("<title>Attention Required! | Cloudflare</title>");
  });
  try {
    /** @type {string[]} */
    const warnings = [];
    const c = await crawlSite(
      `${site.base}/`,
      { pages: 20, crawl: "links", all: true, delay: 0, concurrency: 1 },
      { warn: (m) => warnings.push(m) },
    );
    assert.match(c.stoppedReason, /3 pages in a row were blocked \(Cloudflare firewall block \(HTTP 403\)\)/);
    const requested = [...site.hits.keys()].filter((p) => /^\/p\d$/.test(p));
    assert.equal(requested.length, 3, `only three blocked pages were requested: ${requested.join(",")}`);
    assert.ok(warnings.some((w) => /firewall or CDN is turning requests away/.test(w)));
    assert.ok(c.failures.some((f) => /Cloudflare firewall block/.test(f.error)));
  } finally {
    await site.close();
  }
});
