/**
 * Start a server whose handler decides each response.
 * @param {(req: import("node:http").IncomingMessage, res: import("node:http").ServerResponse, hits: Map<string, number>) => void} handler
 */
function serve(handler) {
  /** @type {Map<string, number>} */
  const hits = new Map();
  return new Promise((resolve) => {
    const server = createServer((req, res) => {
      const path = new URL(req.url ?? "/", "http://x").pathname;
      hits.set(path, (hits.get(path) ?? 0) + 1);
      handler(req, res, hits);
    });
    server.listen(0, "127.0.0.1", () => {
      const base = `http://127.0.0.1:${/** @type {any} */ (server.address()).port}`;
      resolve({
        base,
        hits,
        close: () =>
          new Promise((done) => {
            server.closeAllConnections?.();
            server.close(() => done(undefined));
          }),
      });
    });
  });
}

/** @param {string} title @param {string} body */
const html = (title, body) =>
  `<!doctype html><html lang="en"><head><meta charset="utf-8"><title>${title}</title></head><body><h1>${title}</h1>${body}</body></html>`;

test("parseRetryAfter reads seconds and HTTP dates, and rejects junk", () => {
  const now = Date.parse("2026-11-13T10:00:00Z");
  assert.equal(parseRetryAfter("120", now), 120);
  assert.equal(parseRetryAfter(" 1.5 ", now), 1.5);
  assert.equal(parseRetryAfter("-5", now), 0);
  assert.equal(parseRetryAfter("Fri, 13 Nov 2026 10:00:30 GMT", now), 30);
  assert.equal(parseRetryAfter("Thu, 12 Nov 2026 10:00:00 GMT", now), 0, "a past date means now");
  assert.equal(parseRetryAfter("", now), null);
  assert.equal(parseRetryAfter(undefined, now), null);
  assert.equal(parseRetryAfter("soon", now), null);
  assert.equal(parseRetryAfter("12 34", now), null);
});

test("LatencyThrottle paces a host only after a sustained slow streak, then lets go", () => {
  const t = new LatencyThrottle();
  t.record("a.test", 4);
  t.record("a.test", 4);
  assert.equal(t.gap("a.test"), 0, "two slow pages are not a streak");
  t.record("a.test", 4);
  assert.ok(t.isSlow("a.test"));
  assert.ok(Math.abs(t.gap("a.test") - 2) < 0.01, "gap ≈ average / 2 in flight");
  assert.match(t.popNotices()[0] ?? "", /answering slowly/);
  assert.deepEqual(t.popNotices(), [], "notices are consumed");
  for (let i = 0; i < 12; i++) t.record("a.test", 0.1);
  assert.equal(t.gap("a.test"), 0);
  assert.match(t.popNotices().join(" "), /quickly again/);
  t.record("b.test", 100);
  t.record("b.test", 100);
  t.record("b.test", 100);
  assert.equal(t.gap("b.test"), LatencyThrottle.MAX_GAP, "the gap is capped");
  t.record("c.test", -1);
  t.record("c.test", Number.NaN);
  assert.equal(t.average("c.test"), null, "nonsense timings are ignored");

  const off = new LatencyThrottle(false);
  for (let i = 0; i < 5; i++) off.record("a.test", 9);
  assert.equal(off.gap("a.test"), 0);
  assert.equal(off.isSlow("a.test"), false);
});

test("firewall block pages and CDN challenges are recognised (detection only)", () => {
  assert.equal(detectWafBlock(403, "<p>Generated by Wordfence</p>"), "wordfence");
  assert.equal(detectWafBlock(403, "<title>Attention Required! | Cloudflare</title>"), "cloudflare");
  assert.equal(detectWafBlock(403, "Sucuri WebSite Firewall - Access Denied"), "sucuri");
  assert.equal(detectWafBlock(503, "SiteGround security: request blocked"), "siteground");
  assert.equal(detectWafBlock(200, "wordfence"), "", "a 200 is never a block page");
  assert.equal(detectWafBlock(403, "plain forbidden"), "");

  assert.equal(isChallengeResponse(200, { "cf-mitigated": "challenge" }, ""), true);
  assert.equal(isChallengeResponse(403, {}, '<script src="/cdn-cgi/challenge-platform/x.js">'), true);
  assert.equal(isChallengeResponse(503, { server: "cloudflare" }, "<title>Just a moment...</title>"), true);
  assert.equal(isChallengeResponse(503, { server: "nginx" }, "<title>Just a moment...</title>"), false);
  assert.equal(isChallengeResponse(404, { server: "cloudflare" }, "Just a moment"), false);

  assert.equal(
    protectionNote(403, { server: "cloudflare", "cf-mitigated": "challenge" }, ""),
    "Cloudflare bot challenge (HTTP 403)",
  );
  assert.equal(protectionNote(403, {}, "Generated by Wordfence"), "Wordfence firewall block (HTTP 403)");
  assert.equal(protectionNote(500, {}, "oops"), "");
  assert.equal(headerValue({ "Retry-After": "3" }, "retry-after"), "3");
  assert.equal(headerValue(null, "x"), "");
});

test("withRetries retries rate limits with back-off and honours Retry-After", async () => {
  /** @type {number[]} */
  const waits = [];
  const sleep = async (/** @type {number} */ ms) => void waits.push(ms);
  const responses = [
    { status: 503, headers: {}, html: "" },
    { status: 429, headers: { "retry-after": "3" }, html: "" },
    { status: 200, headers: {}, html: "ok" },
  ];
  /** @type {any[]} */
  const retried = [];
  const r = await withRetries(async () => /** @type {any} */ (responses.shift()), "https://a.test/", {
    sleep,
    baseDelayMs: 100,
    onRetry: (info) => retried.push(info),
  });
  assert.equal(r.result.status, 200);
  assert.equal(r.attempts, 2);
  assert.deepEqual(waits, [100, 3000], "exponential back-off, then the server's Retry-After");
  assert.deepEqual(
    retried.map((x) => [x.status, x.attempt]),
    [
      [503, 1],
      [429, 2],
    ],
  );

  // Gives up after `retries` and returns the last answer.
  let calls = 0;
  const gaveUp = await withRetries(async () => (calls++, { status: 502 }), "u", { retries: 1, sleep });
  assert.equal(gaveUp.result.status, 502);
  assert.equal(calls, 2);

  // retries: 0 disables, a 404 is never retried.
  calls = 0;
  await withRetries(async () => (calls++, { status: 503 }), "u", { retries: 0, sleep });
  await withRetries(async () => (calls++, { status: 404 }), "u", { sleep });
  assert.equal(calls, 2);

  // A firewall block or CDN challenge is never retried.
  calls = 0;
  const blocked = await withRetries(
    async () => (
      calls++,
      { status: 503, headers: { server: "cloudflare" }, html: "<title>Just a moment...</title>" }
    ),
    "u",
    { sleep },
  );
  assert.equal(calls, 1);
  assert.equal(blocked.note, "Cloudflare bot challenge (HTTP 503)");

  // A Retry-After longer than the cap is reported, not waited out.
  const longWait = await withRetries(async () => ({ status: 429, headers: { "retry-after": "3600" } }), "u", {
    sleep,
  });
  assert.match(longWait.note, /retry after 3600s/);

  // A dropped connection is retried once more like a gateway error.
  calls = 0;
  const reset = await withRetries(
    async () => (calls++ === 0 ? { status: 0, error: "socket hang up" } : { status: 200 }),
    "u",
    { sleep },
  );
  assert.equal(reset.result.status, 200);
});

test("crawlTrapReason refuses feeds, APIs, page-builder pagination and repeated segments", () => {
  assert.match(crawlTrapReason("https://a.test/wp-json/wp/v2/posts"), /not a page \(\/wp-json\/\)/);
  assert.match(crawlTrapReason("https://a.test/blog/feed/"), /\/feed\//);
  assert.match(crawlTrapReason("https://a.test/blog/feed"), /\/feed\//, "a feed without the slash");
  assert.match(crawlTrapReason("https://a.test/cdn-cgi/l/email-protection"), /cdn-cgi/);
  assert.match(crawlTrapReason("https://a.test/sitemap_index.xml"), /sitemap file/);
  assert.match(
    crawlTrapReason("https://a.test/news/?e-page-0b1537f=4"),
    /page-builder parameter \(e-page-\*\)/,
  );
  assert.match(crawlTrapReason("https://a.test/shop/?e-filter-abc123=red"), /e-filter/);
  assert.match(crawlTrapReason("https://a.test/blog/?infinity=scrolling"), /infinity/);
  assert.match(crawlTrapReason("https://a.test/shop/?add-to-cart=12"), /action link/);
  assert.match(crawlTrapReason("https://a.test/our-team/our-team/"), /repeated path segment \(our-team\)/);
  assert.match(crawlTrapReason("https://a.test/case-studies/x/case-studies/"), /case-studies/);
  for (const ok of [
    "https://a.test/",
    "https://a.test/2026/01/01/post/",
    "https://a.test/a/b/a/b/",
    "https://a.test/feedback/",
    "https://a.test/blog/?page=2",
    "not a url",
  ]) {
    assert.equal(crawlTrapReason(ok), "", ok);
  }
});

