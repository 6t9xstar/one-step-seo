  assert.equal(hasUnresolvedTemplate("https://a.test/how-to-handle-null"), false);
  assert.equal(hasUnresolvedTemplate("https://a.test/annulled"), false);

  assert.equal(isDevOrStagingHost("localhost", "example.com"), true);
